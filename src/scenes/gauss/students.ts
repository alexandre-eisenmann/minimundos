export function pairsFor(n: number) {
  if (!Number.isInteger(n) || n < 1 || n > 100)
    throw new RangeError('Choose a whole number from 1 to 100.');
  return Array.from(
    { length: Math.floor(n / 2) },
    (_, i) => [i + 1, n - i] as const,
  );
}
export function pairedSum(n: number) {
  const pairs = pairsFor(n);
  return (
    pairs.reduce((sum, [a, b]) => sum + a + b, 0) + (n % 2 ? (n + 1) / 2 : 0)
  );
}
